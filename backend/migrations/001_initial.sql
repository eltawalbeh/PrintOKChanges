CREATE TABLE IF NOT EXISTS printok_settings (
  id smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  shop_name text NOT NULL DEFAULT 'مطبعة المدى',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO printok_settings(id,shop_name) VALUES (1,'مطبعة المدى') ON CONFLICT(id) DO NOTHING;

CREATE TABLE IF NOT EXISTS printok_orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_number bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1025) UNIQUE,
  client_name text NOT NULL CHECK(length(trim(client_name)) BETWEEN 1 AND 160),
  client_phone text NOT NULL CHECK(length(trim(client_phone)) BETWEEN 7 AND 32),
  product_name text NOT NULL CHECK(length(trim(product_name)) BETWEEN 1 AND 240),
  quantity integer NOT NULL CHECK(quantity BETWEEN 1 AND 100000000),
  dimensions text NOT NULL DEFAULT '',
  material text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','pending','approved','changes')),
  current_version integer NOT NULL DEFAULT 0 CHECK(current_version >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS printok_orders_updated_idx ON printok_orders(updated_at DESC);
CREATE INDEX IF NOT EXISTS printok_orders_status_idx ON printok_orders(status,created_at DESC);

CREATE TABLE IF NOT EXISTS printok_versions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id uuid NOT NULL REFERENCES printok_orders(id) ON DELETE CASCADE,
  version_number integer NOT NULL CHECK(version_number > 0),
  status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','changes')),
  file_key text NOT NULL,
  file_name text NOT NULL,
  file_type text NOT NULL CHECK(file_type IN ('application/pdf','image/png','image/jpeg')),
  file_size bigint NOT NULL CHECK(file_size BETWEEN 1 AND 20971520),
  review_token_hash char(64) UNIQUE,
  review_expires_at timestamptz,
  review_decision_at timestamptz,
  review_note text,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(order_id,version_number)
);
CREATE INDEX IF NOT EXISTS printok_versions_order_idx ON printok_versions(order_id,version_number DESC);

CREATE TABLE IF NOT EXISTS printok_sessions (
  token_hash char(64) PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  last_seen_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS printok_sessions_exp_idx ON printok_sessions(expires_at);

CREATE TABLE IF NOT EXISTS printok_login_attempts (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ip_hash char(64) NOT NULL,
  success boolean NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS printok_login_ip_idx ON printok_login_attempts(ip_hash,created_at DESC);

CREATE TABLE IF NOT EXISTS printok_events (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  order_id uuid REFERENCES printok_orders(id) ON DELETE SET NULL,
  version_id uuid REFERENCES printok_versions(id) ON DELETE SET NULL,
  event_type text NOT NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS printok_events_created_idx ON printok_events(created_at DESC);
